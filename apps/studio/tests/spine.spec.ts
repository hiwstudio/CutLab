import { expect, test } from "@playwright/test";
import { FIXTURE } from "./global-setup";

test("Spine: scene review, linked reorder, mixer, history and saved layout", async ({ page, request }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto("/");
  await page.getByTestId("new-project-name").fill("Spine Workspace");
  await page.getByTestId("create-project").click();
  await page.waitForURL(/\/p\/proj_/);
  const id = page.url().split("/p/")[1];
  const base = `http://127.0.0.1:8787/api/v1/projects/${id}`;
  await page.getByTestId("upload-input").setInputFiles(FIXTURE);
  const asset = page.locator("[data-testid^=asset-ast_]");
  await expect(asset).toHaveAttribute("data-asset-status", "ready", { timeout: 90_000 });
  await asset.dblclick();
  await expect(page.locator("[data-clip-id]")).toHaveCount(1);
  const clip = await page.locator("[data-clip-id]").getAttribute("data-clip-id");
  const project = await (await request.get(base)).json();
  const result = await request.post(`${base}/apply`, { data: { base_rev: project.head_rev, ops: [{ op: "split", clip, at_ms: 2000 }] } });
  expect(result.ok()).toBeTruthy();
  await page.reload();
  await page.getByRole("button", { name: "Scenes", exact: true }).click();
  await page.getByRole("button", { name: "Create scenes from video cuts" }).click();
  const scenes = page.locator(".spine-scene");
  await expect(scenes).toHaveCount(2);
  await scenes.first().click();
  await page.getByRole("button", { name: "Approve scene", exact: true }).click();
  await expect(page.getByRole("button", { name: "✓ Approved · reopen" })).toBeVisible();
  await page.getByText("Scene settings", { exact: true }).click();
  await page.getByLabel("Scene title").fill("Opening moment");
  await page.getByRole("button", { name: "Save title", exact: true }).click();
  await expect(scenes.first()).toContainText("Opening moment");
  await expect(page.getByRole("button", { name: "Approve scene", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Later →", exact: true }).click();
  await expect(scenes.nth(1)).toContainText("Opening moment");
  await scenes.nth(1).click();
  await page.getByRole("button", { name: "Audio", exact: true }).click();
  const strip = page.locator(".spine-track").first();
  await strip.getByLabel("Track name").fill("Main footage");
  await strip.getByLabel("Track gain · dB").fill("-6");
  await strip.getByRole("button", { name: "Save track" }).click();
  await expect(page.locator("[data-track-kind=video]").first().locator("..")).toContainText("Main footage");
  await strip.getByRole("button", { name: "Mute", exact: true }).click();
  await expect(page.locator("audio[data-testid^=audio-]")).toHaveCount(0);
  await strip.getByRole("button", { name: "Mute", exact: true }).click();
  await expect(page.locator("audio[data-testid^=audio-]")).toHaveCount(1);
  await page.getByTestId("play-button").click();
  await expect.poll(() => page.locator("audio[data-testid^=audio-]").evaluateAll(els => els.some(el => !(el as HTMLAudioElement).paused))).toBe(true);
  await page.getByTestId("play-button").click();
  await strip.getByRole("button", { name: "Lock", exact: true }).click();
  await expect(strip.getByLabel("Track name")).toBeDisabled();
  await strip.getByRole("button", { name: "Unlock", exact: true }).click();
  await page.getByRole("button", { name: "History", exact: true }).click();
  await page.getByTestId("revision-list").getByRole("button").nth(1).click();
  await expect(page.getByTestId("director-input")).toBeDisabled();
  await page.getByRole("button", { name: "Return to current edit" }).click();
  await page.getByRole("button", { name: "Lens", exact: true }).click();
  await scenes.first().click();
  await page.getByRole("button", { name: "Fit", exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: testInfo.outputPath("spine-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 1100, height: 760 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: testInfo.outputPath("spine-compact.png"), fullPage: true });
  await page.reload();
  await expect(page.locator(".spine-scene").nth(1)).toContainText("Opening moment");
  expect(errors).toEqual([]);
});
